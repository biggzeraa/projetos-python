num=int(input("Digite um número positivo maior que zero: "))

if(num >0):
    print("O seu número: ", num ," é positivo e maior que zero.")
    print("O seu número ao quadrado: ", num * num)
    print("O seu número ao cubo: ", num * num * num)

else:
    print("O seu número: ", num ," é menor ou igual a zero.")